#!/usr/bin/env python3
"""
Compute average DEG/HVG/L1000 Venn diagrams using seurat_dispersion HVGs.

This script follows the region definitions from 004.compute_hvg_l1000_deg_venn.py,
but uses HVG files generated by sc.pp.highly_variable_genes(flavor="seurat")
which are stored in the seurat_dispersion HVG folders.
"""
from __future__ import annotations

import argparse
import gc
import re
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence, Set, Tuple

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
from matplotlib_venn import venn3

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
OUT_DIR = ROOT / "results" / "013.seurat_dispersion_hvg_l1000_deg_average_venn"
L1000_MAPPED = ROOT / "results" / "004.hvg_l1000_deg_venn" / "L1000_landmark_mapped_to_ensg.csv"

DATASETS = ("OTF", "sciplex", "tahoe")
TOP_NS = (2000, 3000, 5000, 10000)
HVG_LEVELS = ("dataset", "cellline")

DEG_FILES = {
    "OTF": DATA_DIR / "OTF_filtered_deg_fdr0.05_log2fc0.144_abs.csv",
    "sciplex": DATA_DIR / "sciplex_filtered_deg_fdr0.05_log2fc0.144_abs.csv",
    "tahoe": DATA_DIR / "tahoe_filtered_deg_fdr0.05_log2fc0.144_abs.csv",
}

HVG_DIRS = {
    "dataset": DATA_DIR / "002.dataset_hvg_seurat_dispersion",
    "cellline": DATA_DIR / "002.cellline_hvg_seurat_dispersion",
}


def normalise_gene_id(value: object) -> Optional[str]:
    if pd.isna(value):
        return None
    text = str(value).strip()
    if not text:
        return None
    return text.split(".")[0]


def load_l1000_genes(path: Path) -> Set[str]:
    if not path.exists():
        raise FileNotFoundError(f"Missing mapped L1000 file: {path}")
    df = pd.read_csv(path)
    if "ensembl_gene_ids" not in df.columns:
        raise ValueError(f"{path} does not contain ensembl_gene_ids")
    genes: Set[str] = set()
    for value in df["ensembl_gene_ids"].dropna():
        for part in str(value).split("|"):
            gene = normalise_gene_id(part)
            if gene:
                genes.add(gene)
    if not genes:
        raise ValueError(f"No L1000 genes found in {path}")
    return genes


def find_gene_column(columns: Sequence[str]) -> str:
    for col in ("gene_id", "ensembl_gene_id", "ensembl_id", "gene", "genes"):
        if col in columns:
            return col
    raise ValueError(f"Cannot identify gene column in columns: {list(columns)}")


def load_hvg_genes(path: Path) -> Set[str]:
    df = pd.read_csv(path)
    gene_col = find_gene_column(df.columns)
    return {gene for gene in (normalise_gene_id(x) for x in df[gene_col]) if gene}


def parse_cell_id_from_hvg(path: Path, dataset: str) -> Optional[str]:
    pattern = re.compile(rf"^{re.escape(dataset)}_(.+)_top(?:2000|3000|5000|10000)_hvg\.csv$")
    match = pattern.match(path.name)
    return match.group(1) if match else None


def discover_hvg_manifest(levels: Iterable[str], top_ns: Iterable[int], datasets: Iterable[str]) -> pd.DataFrame:
    records: List[dict] = []
    for level in levels:
        hvg_dir = HVG_DIRS[level]
        for dataset in datasets:
            for top_n in top_ns:
                if level == "dataset":
                    path = hvg_dir / f"{dataset}_top{top_n}_hvg.csv"
                    if path.exists():
                        records.append({
                            "dataset": dataset,
                            "hvg_level": level,
                            "hvg_top_n": top_n,
                            "cell_id": "__dataset__",
                            "hvg_file": str(path),
                        })
                else:
                    for path in sorted(hvg_dir.glob(f"{dataset}_*_top{top_n}_hvg.csv")):
                        cell_id = parse_cell_id_from_hvg(path, dataset)
                        if cell_id:
                            records.append({
                                "dataset": dataset,
                                "hvg_level": level,
                                "hvg_top_n": top_n,
                                "cell_id": cell_id,
                                "hvg_file": str(path),
                            })
    return pd.DataFrame.from_records(records)


def load_deg_groups(dataset: str, path: Path, chunksize: int) -> Dict[Tuple[str, str, str], Set[str]]:
    if not path.exists():
        raise FileNotFoundError(f"Missing DEG file for {dataset}: {path}")
    groups: Dict[Tuple[str, str, str], Set[str]] = {}
    usecols = ["cell_id", "cell_type", "perturbation_id", "gene_id"]
    for chunk in pd.read_csv(path, usecols=usecols, chunksize=chunksize):
        chunk["gene_id"] = chunk["gene_id"].map(normalise_gene_id)
        chunk = chunk.dropna(subset=["gene_id", "cell_id", "perturbation_id"])
        for (cell_id, cell_type, perturbation_id), sub in chunk.groupby(["cell_id", "cell_type", "perturbation_id"], sort=False):
            key = (str(cell_id), str(cell_type), str(perturbation_id))
            groups.setdefault(key, set()).update(sub["gene_id"].astype(str))
    return groups


def intersection_counts(deg: Set[str], hvg: Set[str], l1000: Set[str]) -> dict:
    deg_hvg = deg & hvg
    deg_l1000 = deg & l1000
    hvg_l1000 = hvg & l1000
    all3 = deg & hvg & l1000
    return {
        "deg_n": len(deg),
        "hvg_n": len(hvg),
        "l1000_n": len(l1000),
        "deg_hvg_n": len(deg_hvg),
        "deg_l1000_n": len(deg_l1000),
        "hvg_l1000_n": len(hvg_l1000),
        "deg_hvg_l1000_n": len(all3),
        "deg_hvg_fraction_of_deg": len(deg_hvg) / len(deg) if deg else 0.0,
        "deg_l1000_fraction_of_deg": len(deg_l1000) / len(deg) if deg else 0.0,
        "deg_hvg_l1000_fraction_of_deg": len(all3) / len(deg) if deg else 0.0,
        "deg_only_n": len(deg - hvg - l1000),
        "hvg_only_n": len(hvg - deg - l1000),
        "l1000_only_n": len(l1000 - deg - hvg),
        "deg_hvg_only_n": len(deg_hvg - l1000),
        "deg_l1000_only_n": len(deg_l1000 - hvg),
        "hvg_l1000_only_n": len(hvg_l1000 - deg),
    }


def add_all_dataset_average(summary: pd.DataFrame, group_cols: List[str], value_cols: List[str]) -> pd.DataFrame:
    all_group_cols = [col for col in group_cols if col != "dataset"]
    agg = summary.groupby(all_group_cols, dropna=False)[value_cols].mean().reset_index()
    agg.insert(0, "dataset", "all")
    return pd.concat([summary, agg[group_cols + value_cols]], ignore_index=True)


def format_avg(value: float) -> str:
    if pd.isna(value):
        return "0"
    if abs(value - round(value)) < 0.05:
        return str(int(round(value)))
    return f"{value:.1f}"


def plot_average_venns(summary: pd.DataFrame, out_dir: Path, formats: Sequence[str]) -> None:
    average_dir = out_dir / "average_venn"
    average_dir.mkdir(parents=True, exist_ok=True)
    labels = ("DEG", "HVG\nseurat_dispersion", "L1000")
    region_cols = [
        "deg_only_n",
        "hvg_only_n",
        "deg_hvg_only_n",
        "l1000_only_n",
        "deg_l1000_only_n",
        "hvg_l1000_only_n",
        "deg_hvg_l1000_n",
    ]
    for _, row in summary.iterrows():
        subsets = tuple(float(row[col]) for col in region_cols)
        fig, ax = plt.subplots(figsize=(6.5, 6.0))
        venn = venn3(subsets=subsets, set_labels=labels, ax=ax)
        for region_id, value in zip(("100", "010", "110", "001", "101", "011", "111"), subsets):
            label = venn.get_label_by_id(region_id) if venn else None
            if label is not None:
                label.set_text(format_avg(value))
                label.set_fontsize(9)
        for label in venn.set_labels if venn and venn.set_labels else []:
            if label is not None:
                label.set_fontsize(11)
        title = f"{row['dataset']} | {row['hvg_level']} top{int(row['hvg_top_n'])} | average per perturbation"
        ax.set_title(title, fontsize=12)
        fig.tight_layout()
        base = average_dir / f"{row['dataset']}__seurat_dispersion__{row['hvg_level']}__top{int(row['hvg_top_n'])}__average_venn"
        for fmt in formats:
            fig.savefig(base.with_suffix(f".{fmt}"), dpi=300, bbox_inches="tight")
        plt.close(fig)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, default=OUT_DIR)
    parser.add_argument("--chunksize", type=int, default=1_000_000)
    parser.add_argument("--formats", nargs="+", default=["png", "pdf"], choices=["png", "pdf", "svg"])
    parser.add_argument("--datasets", nargs="+", default=list(DATASETS), choices=list(DATASETS))
    parser.add_argument("--levels", nargs="+", default=list(HVG_LEVELS), choices=list(HVG_LEVELS))
    parser.add_argument("--top-ns", nargs="+", type=int, default=list(TOP_NS))
    args = parser.parse_args()

    out_dir: Path = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    l1000 = load_l1000_genes(L1000_MAPPED)
    manifest = discover_hvg_manifest(args.levels, args.top_ns, args.datasets)
    if manifest.empty:
        raise RuntimeError("No seurat_dispersion HVG files were found")
    manifest.to_csv(out_dir / "seurat_dispersion_hvg_manifest.csv", index=False)

    all_rows: List[pd.DataFrame] = []
    skipped_rows: List[dict] = []
    hvg_cache: Dict[str, Set[str]] = {}

    for dataset in args.datasets:
        print(f"[INFO] Loading DEG groups for {dataset}", flush=True)
        deg_groups = load_deg_groups(dataset, DEG_FILES[dataset], args.chunksize)
        dataset_manifest = manifest[manifest["dataset"] == dataset].copy()
        rows: List[dict] = []
        for _, hvg_meta in dataset_manifest.iterrows():
            hvg_file = hvg_meta["hvg_file"]
            if hvg_file not in hvg_cache:
                hvg_cache[hvg_file] = load_hvg_genes(Path(hvg_file))
            hvg = hvg_cache[hvg_file]
            level = hvg_meta["hvg_level"]
            target_cell = hvg_meta["cell_id"]
            matched = 0
            for (cell_id, cell_type, perturbation_id), deg in deg_groups.items():
                if level == "cellline" and cell_id != target_cell:
                    continue
                counts = intersection_counts(deg, hvg, l1000)
                rows.append({
                    "dataset": dataset,
                    "cell_id": cell_id,
                    "cell_type": cell_type,
                    "perturbation_id": perturbation_id,
                    "hvg_method": "seurat_dispersion",
                    "hvg_level": level,
                    "hvg_top_n": int(hvg_meta["hvg_top_n"]),
                    "hvg_file": hvg_file,
                    **counts,
                })
                matched += 1
            if matched == 0:
                skipped_rows.append({
                    "dataset": dataset,
                    "hvg_level": level,
                    "hvg_top_n": int(hvg_meta["hvg_top_n"]),
                    "cell_id": target_cell,
                    "hvg_file": hvg_file,
                    "reason": "no_matching_deg_group",
                })
        if rows:
            all_rows.append(pd.DataFrame.from_records(rows))
        print(f"[INFO] Finished {dataset}: {len(rows)} rows", flush=True)
        del deg_groups
        gc.collect()

    if not all_rows:
        raise RuntimeError("No intersections were computed")

    counts = pd.concat(all_rows, ignore_index=True)
    counts_path = out_dir / "seurat_dispersion_intersection_counts.csv"
    counts.to_csv(counts_path, index=False)

    if skipped_rows:
        pd.DataFrame.from_records(skipped_rows).to_csv(out_dir / "skipped_manifest.csv", index=False)
    else:
        pd.DataFrame(columns=["dataset", "hvg_level", "hvg_top_n", "cell_id", "hvg_file", "reason"]).to_csv(out_dir / "skipped_manifest.csv", index=False)

    value_cols = [
        "deg_only_n",
        "hvg_only_n",
        "deg_hvg_only_n",
        "l1000_only_n",
        "deg_l1000_only_n",
        "hvg_l1000_only_n",
        "deg_hvg_l1000_n",
        "deg_n",
        "hvg_n",
        "l1000_n",
        "deg_hvg_n",
        "deg_l1000_n",
        "hvg_l1000_n",
        "deg_hvg_fraction_of_deg",
        "deg_l1000_fraction_of_deg",
        "deg_hvg_l1000_fraction_of_deg",
    ]
    group_cols = ["dataset", "hvg_method", "hvg_level", "hvg_top_n"]
    summary = counts.groupby(group_cols, dropna=False)[value_cols].mean().reset_index()
    summary = add_all_dataset_average(summary, group_cols, value_cols)
    summary_path = out_dir / "seurat_dispersion_average_intersection_summary.csv"
    summary.to_csv(summary_path, index=False)

    plot_average_venns(summary, out_dir, args.formats)
    print(f"[DONE] counts: {counts_path}", flush=True)
    print(f"[DONE] summary: {summary_path}", flush=True)
    print(f"[DONE] average venns: {out_dir / 'average_venn'}", flush=True)


if __name__ == "__main__":
    main()
